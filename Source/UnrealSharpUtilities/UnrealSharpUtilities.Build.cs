using UnrealBuildTool;

using System.IO;
using System.Security;
using EpicGames.Core;

public class UnrealSharpUtilities : ModuleRules
{
    public UnrealSharpUtilities(ReadOnlyTargetRules Target) : base(Target)
    {
        PCHUsage = PCHUsageMode.UseExplicitOrSharedPCHs;

        PublicDependencyModuleNames.AddRange(
            new string[]
            {
                "Core", 
                "Json", 
                "Projects",
            }
        );

        PrivateDependencyModuleNames.AddRange(
            new string[]
            {
                "CoreUObject",
                "Engine",
                "Slate",
                "SlateCore",
                "DeveloperSettings",
                "Projects", 
            }
        );

        if (Target.bBuildEditor)
        {
            PublicDependencyModuleNames.AddRange(
                new string[]
                {
                    "UATHelper",
                    "UnrealEd",
                }
            );
        }
        
        PublicDefinitions.Add("ForceAsEngineGlue=1");

        RegisterStagingAutomation(Target);
    }

    private void RegisterStagingAutomation(ReadOnlyTargetRules Target)
    {
        // Source-engine UAT scans project Build directories but not project plugins.
        // Engine plugins are already discovered; UE 5.6 uses an explicit UAT hook.
        if (Target.ProjectFile == null ||
            new DirectoryReference(PluginDirectory).IsUnderDirectory(new DirectoryReference(EngineDirectory)) ||
            !File.Exists(Path.Combine(EngineDirectory, "Source", "Programs", "AutomationTool", "AutomationUtils", "CustomStagingHandler.cs")))
        {
            return;
        }

        string Template = Path.Combine(PluginDirectory, "Build", "Staging", "UnrealSharpProject.Automation.csproj.template");
        ExternalDependencies.Add(Template);
        string BuildDirectory = Path.Combine(Target.ProjectFile.Directory.FullName, "Build", "UnrealSharp");
        string ProjectFile = Path.Combine(BuildDirectory, "UnrealSharpProject.Automation.csproj");
        const string Marker = "<!-- Generated by UnrealSharp. -->";
        if (File.Exists(ProjectFile) && !File.ReadAllText(ProjectFile).StartsWith(Marker, System.StringComparison.Ordinal))
        {
            throw new BuildException("UnrealSharp cannot generate staging automation over the existing file '{0}'. Move or rename that file first.", ProjectFile);
        }

        string RelativePluginDirectory = Path.GetRelativePath(BuildDirectory, PluginDirectory).Replace('\\', '/');
        // MSBuild escaping precedes XML escaping for paths containing special characters.
        foreach (char Character in new[] { '%', '$', '@', ';', '\'', '(', ')', '?', '*' })
        {
            RelativePluginDirectory = RelativePluginDirectory.Replace(Character.ToString(), "%" + ((int)Character).ToString("X2"));
        }
        string Contents = File.ReadAllText(Template).Replace("__UNREALSHARP_DIRECTORY__", SecurityElement.Escape(RelativePluginDirectory));
        if (!File.Exists(ProjectFile) || File.ReadAllText(ProjectFile) != Contents)
        {
            Directory.CreateDirectory(BuildDirectory);
            File.WriteAllText(ProjectFile, Contents);
        }
        ExternalDependencies.Add(ProjectFile);
    }
}
